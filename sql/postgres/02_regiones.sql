\set ON_ERROR_STOP on

-- --------------------------------------------------------------------------
-- Segmentacion horizontal: cada region tiene su propio esquema y sus
-- propias tablas operativas. Los identificadores usan rangos distintos para
-- mantener unicidad global (10xxx, 20xxx, 30xxx).
-- --------------------------------------------------------------------------
DO $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT * FROM (VALUES
            ('san_jose', 1, 10001),
            ('alajuela', 2, 20001),
            ('cartago',  3, 30001)
        ) AS t(esquema, id_sucursal, id_inicio)
    LOOP
        EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I', r.esquema);

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.pacientes (
                id_paciente      integer GENERATED BY DEFAULT AS IDENTITY (START WITH %s) PRIMARY KEY,
                cedula           varchar(20)  NOT NULL,
                nombre           varchar(120) NOT NULL,
                apellidos        varchar(120) NOT NULL,
                fecha_nacimiento date         NOT NULL,
                sexo             varchar(1)   NOT NULL,
                telefono         varchar(20),
                email            varchar(120),
                direccion        text,
                id_sucursal      integer      NOT NULL REFERENCES catalogo.sucursal (id_sucursal),
                creado_en        timestamptz  NOT NULL DEFAULT now(),
                CONSTRAINT uq_%s_paciente_cedula UNIQUE (cedula),
                CONSTRAINT ck_%s_paciente_sexo CHECK (sexo IN ('M', 'F', 'O')),
                CONSTRAINT ck_%s_paciente_sucursal CHECK (id_sucursal = %s)
            )
        $ddl$, r.esquema, r.id_inicio, r.esquema, r.esquema, r.esquema, r.id_sucursal);

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.citas (
                id_cita    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_paciente integer NOT NULL REFERENCES %I.pacientes (id_paciente) ON DELETE CASCADE,
                id_medico  integer NOT NULL REFERENCES catalogo.medico (id_medico),
                fecha_hora timestamptz NOT NULL,
                estado     varchar(20) NOT NULL DEFAULT 'PROGRAMADA',
                motivo     text,
                creado_en  timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT ck_%s_cita_estado
                    CHECK (estado IN ('PROGRAMADA', 'ATENDIDA', 'CANCELADA', 'REPROGRAMADA'))
            )
        $ddl$, r.esquema, r.esquema, r.esquema);

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.ordenes (
                id_orden    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_cita     integer REFERENCES %I.citas (id_cita) ON DELETE SET NULL,
                id_paciente integer NOT NULL REFERENCES %I.pacientes (id_paciente) ON DELETE CASCADE,
                fecha       timestamptz NOT NULL DEFAULT now(),
                estado      varchar(20) NOT NULL DEFAULT 'ABIERTA',
                CONSTRAINT ck_%s_orden_estado
                    CHECK (estado IN ('ABIERTA', 'PROCESADA', 'ANULADA'))
            )
        $ddl$, r.esquema, r.esquema, r.esquema, r.esquema);

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.estudios (
                id_estudio   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_orden     integer NOT NULL REFERENCES %I.ordenes (id_orden) ON DELETE CASCADE,
                id_paciente  integer NOT NULL REFERENCES %I.pacientes (id_paciente) ON DELETE CASCADE,
                id_tipo      integer NOT NULL REFERENCES catalogo.tipo_estudio (id_tipo),
                id_medico    integer NOT NULL REFERENCES catalogo.medico (id_medico),
                fecha        timestamptz NOT NULL DEFAULT now(),
                estado       varchar(20) NOT NULL DEFAULT 'PENDIENTE',
                resultado    jsonb,
                observaciones text,
                CONSTRAINT ck_%s_estudio_estado
                    CHECK (estado IN ('PENDIENTE', 'EN_PROCESO', 'COMPLETADO', 'ENTREGADO'))
            )
        $ddl$, r.esquema, r.esquema, r.esquema, r.esquema);

        EXECUTE format($ddl$
            CREATE TABLE IF NOT EXISTS %I.diagnosticos (
                id_diagnostico integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                id_estudio     integer NOT NULL REFERENCES %I.estudios (id_estudio) ON DELETE CASCADE,
                codigo_cie10   varchar(10) NOT NULL,
                descripcion    text        NOT NULL,
                fecha          timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT uq_%s_diag UNIQUE (id_estudio, codigo_cie10)
            )
        $ddl$, r.esquema, r.esquema, r.esquema);

        EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_citas_fecha ON %I.citas (fecha_hora)', r.esquema, r.esquema);
        EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_estudios_fecha ON %I.estudios (fecha)', r.esquema, r.esquema);
        EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_estudios_paciente ON %I.estudios (id_paciente)', r.esquema, r.esquema);
        EXECUTE format('CREATE INDEX IF NOT EXISTS ix_%s_estudios_medico ON %I.estudios (id_medico)', r.esquema, r.esquema);
    END LOOP;
END $$;

-- --------------------------------------------------------------------------
-- Vistas federadas de la capa local (union de las tres regiones).
-- --------------------------------------------------------------------------
CREATE OR REPLACE VIEW operativo.v_pacientes_todos AS
SELECT 'san_jose'::varchar(40) AS region, p.* FROM san_jose.pacientes p
UNION ALL
SELECT 'alajuela'::varchar(40) AS region, p.* FROM alajuela.pacientes p
UNION ALL
SELECT 'cartago'::varchar(40)  AS region, p.* FROM cartago.pacientes p;

CREATE OR REPLACE VIEW operativo.v_estudios_todos AS
SELECT 'san_jose'::varchar(40) AS region,
       e.id_estudio, e.id_orden, e.id_paciente, e.id_tipo, e.id_medico,
       e.fecha, e.estado, e.resultado, e.observaciones,
       p.nombre || ' ' || p.apellidos AS paciente,
       t.nombre AS tipo, m.nombre AS medico, s.nombre AS sucursal,
       p.id_sucursal,
       dx.codigo_cie10 AS diagnostico
FROM san_jose.estudios e
JOIN san_jose.pacientes p  ON p.id_paciente = e.id_paciente
JOIN catalogo.tipo_estudio t ON t.id_tipo = e.id_tipo
JOIN catalogo.medico m       ON m.id_medico = e.id_medico
JOIN catalogo.sucursal s     ON s.id_sucursal = p.id_sucursal
LEFT JOIN LATERAL (
    SELECT d.codigo_cie10
    FROM san_jose.diagnosticos d
    WHERE d.id_estudio = e.id_estudio
    ORDER BY d.id_diagnostico
    LIMIT 1
) dx ON TRUE
UNION ALL
SELECT 'alajuela'::varchar(40),
       e.id_estudio, e.id_orden, e.id_paciente, e.id_tipo, e.id_medico,
       e.fecha, e.estado, e.resultado, e.observaciones,
       p.nombre || ' ' || p.apellidos,
       t.nombre, m.nombre, s.nombre,
       p.id_sucursal,
       dx.codigo_cie10
FROM alajuela.estudios e
JOIN alajuela.pacientes p  ON p.id_paciente = e.id_paciente
JOIN catalogo.tipo_estudio t ON t.id_tipo = e.id_tipo
JOIN catalogo.medico m       ON m.id_medico = e.id_medico
JOIN catalogo.sucursal s     ON s.id_sucursal = p.id_sucursal
LEFT JOIN LATERAL (
    SELECT d.codigo_cie10
    FROM alajuela.diagnosticos d
    WHERE d.id_estudio = e.id_estudio
    ORDER BY d.id_diagnostico
    LIMIT 1
) dx ON TRUE
UNION ALL
SELECT 'cartago'::varchar(40),
       e.id_estudio, e.id_orden, e.id_paciente, e.id_tipo, e.id_medico,
       e.fecha, e.estado, e.resultado, e.observaciones,
       p.nombre || ' ' || p.apellidos,
       t.nombre, m.nombre, s.nombre,
       p.id_sucursal,
       dx.codigo_cie10
FROM cartago.estudios e
JOIN cartago.pacientes p  ON p.id_paciente = e.id_paciente
JOIN catalogo.tipo_estudio t ON t.id_tipo = e.id_tipo
JOIN catalogo.medico m       ON m.id_medico = e.id_medico
JOIN catalogo.sucursal s     ON s.id_sucursal = p.id_sucursal
LEFT JOIN LATERAL (
    SELECT d.codigo_cie10
    FROM cartago.diagnosticos d
    WHERE d.id_estudio = e.id_estudio
    ORDER BY d.id_diagnostico
    LIMIT 1
) dx ON TRUE;
